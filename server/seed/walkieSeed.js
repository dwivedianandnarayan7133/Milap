async function seedWalkieData() {
  try {
    const mongoUri = process.env.MONGODB_URI || process.env.MONGO_URI;
    if (!mongoUri) {
      console.error("No MONGO_URI found in environment");
      process.exit(1);
    }

    await mongoose.connect(mongoUri);
    console.log("Connected to MongoDB for Walkie-Talkie seed.");

    // Clear existing Walkie data to maintain clean seed
    await WalkieVendor.deleteMany({});
    await WalkieEquipment.deleteMany({});
    console.log("Cleared existing Walkie vendors and equipment.");

    for (const vendorData of SEED_VENDORS) {
      const { equipment, ...vProfile } = vendorData;
      const vendor = await WalkieVendor.create(vProfile);
      console.log(`Seeded vendor: ${vendor.companyName} (${vendor.city})`);

      for (const eq of equipment) {
        await WalkieEquipment.create({
          ...eq,
          vendor: vendor._id,
        });
      }
      console.log(`  └ Seeded ${equipment.length} equipment models.`);
    }

    console.log("Walkie-Talkie seeding completed successfully!");
    process.exit(0);
  } catch (err) {
    console.error("Seeding failed:", err);
    process.exit(1);
  }
}

seedWalkieData();
